"""Generate the course-site walkthrough pages from each lab's source + executed solution notebook.

    python tools/build_lab_pages.py            # all labs → course/walkthrough/<lab>.qmd + course/walkthrough/fig/

Each page shows the notebook top to bottom with its outputs and charts. A TODO cell shows the starter code learners
see in class; the solution sits in a collapsed "ดูเฉลย" box. Run tools/build_lab_nb.py first so the solutions are fresh.
Edit labs/src/<lab>.py, never the generated pages.
"""
from __future__ import annotations

import base64
import re
import shutil
import sys
from pathlib import Path

import nbformat

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_lab_nb import LABS, ROOT, parse, render_code  # noqa: E402

OUT = ROOT / "course" / "walkthrough"
FIG = OUT / "fig"

# lab stem → (page title, theory pages linked under every section: (label, path from course/walkthrough/))
LABS_META = {
    "lab1-logistic": ("Lab 1 · คัดกรองเบาหวานด้วย Logistic Regression",
                      [("M1 · Classification สำหรับงานคัดกรอง", "../m1-classification/index.qmd")]),
    "lab2-random-forest": ("Lab 2 · Random Forest และการเลือก model",
                           [("M2 · Decision tree → Random Forest", "../m2-models/index.qmd")]),
    "lab3-shap": ("Lab 3 · อธิบาย model ด้วย SHAP",
                  [("M3 · SHAP", "../m3-shap/index.qmd")]),
    "lab5-challenge-heart": ("Mini-challenge · คัดกรองโรคหัวใจ",
                             [("M1", "../m1-classification/index.qmd"), ("M2", "../m2-models/index.qmd"),
                              ("M3", "../m3-shap/index.qmd")]),
}

INTRO = """::: {{.callout-note appearance="simple"}}
## ใช้หน้านี้อย่างไร
หน้านี้คือ notebook `labs/{stem}.ipynb` ทั้งหมด พร้อมผลลัพธ์และกราฟ อ่านทวนก่อนหรือหลังคลาสได้
ช่อง TODO แสดงโค้ดตั้งต้นแบบที่เห็นในคลาส คำตอบอยู่ในกล่อง **ดูเฉลย** — ลองคิดเองก่อนเปิด
ลงมือรันจริงใน repo ที่ fork ไว้ ([เตรียมเครื่อง](../setup/github.qmd)) · ตารางเวลาและภาพรวมอยู่ที่ [แผน lab](../labs.qmd)
:::

<!-- generated by tools/build_lab_pages.py from labs/src/{stem}.py — edit the source, not this page -->
"""

# lines that only matter when running the notebook in class
DROP = re.compile(r"^\s*(# ตามไม่ทัน\?.*|# .*= load_checkpoint\(.*\)|save_checkpoint\(.*\))\s*$")
ANSI = re.compile(r"\x1b\[[0-9;]*m")


def clean_code(code: str) -> str:
    lines = [l for l in code.splitlines() if not DROP.match(l)]
    # drop a multi-line save_checkpoint(...) call
    out, skip = [], False
    for l in lines:
        if l.lstrip().startswith("save_checkpoint("):
            skip = not l.rstrip().endswith(")")
            continue
        if skip:
            skip = not l.rstrip().endswith(")")
            continue
        out.append(l)
    return "\n".join(out).strip("\n")


def fence(code: str, lang: str = "python") -> str:
    return f"```{lang}\n{code}\n```\n"


def render_outputs(outputs, stem: str, idx: int) -> str:
    parts, n = [], 0
    for o in outputs:
        t = o.get("output_type")
        if t == "stream":
            if o.get("name") == "stderr":
                continue
            text = ANSI.sub("", o["text"]).rstrip()
            if text:
                parts.append(fence(text, "{.text .cell-output}"))
        elif t in ("execute_result", "display_data"):
            data = o.get("data", {})
            if "image/png" in data:
                n += 1
                name = f"{stem}-c{idx:02d}-{n}.png"
                (FIG / name).write_bytes(base64.b64decode(data["image/png"]))
                parts.append(f"![](fig/{name}){{.cell-figure}}\n")
            elif "text/html" in data and "<table" in data["text/html"] and "sk-" not in data["text/html"]:
                html = data["text/html"]
                html = re.sub(r"<style scoped>.*?</style>", "", html, flags=re.S)
                parts.append(f"::: {{.cell-output-table}}\n```{{=html}}\n{html.strip()}\n```\n:::\n")
            elif "text/plain" in data:
                text = ANSI.sub("", data["text/plain"]).rstrip()
                if text and not text.startswith("<Figure"):
                    parts.append(fence(text, "{.text .cell-output}"))
        elif t == "error":
            parts.append(fence(f"{o['ename']}: {o['evalue']}", "{.text .cell-output}"))
    return "\n".join(parts)


def build(stem: str) -> Path:
    title, theory = LABS_META[stem]
    cells = parse(LABS / "src" / f"{stem}.py")
    sol = nbformat.read(LABS / "solution" / f"{stem}.ipynb", as_version=4)
    code_outputs = [c.get("outputs", []) for c in sol.cells if c.cell_type == "code"][1:]   # [0] = chdir cell
    theory_line = " · ".join(f"[{label}]({path})" for label, path in theory)

    body, ci = [INTRO.format(stem=stem)], 0
    for kind, text in cells:
        if kind == "md":
            lines = text.splitlines()
            if lines and lines[0].startswith("# "):          # notebook title → page title
                lines = lines[1:]
            md = "\n".join(lines).strip()
            md = re.sub(r"^## (\S+) (.*)$", lambda m: f"## {m.group(1)} {m.group(2)} {{#s{m.group(1).replace('.', '-').lower()}}}",
                        md, flags=re.M)
            if md.startswith("## "):
                head, _, rest = md.partition("\n")
                md = f"{head}\n\n::: {{.theory-link}}\nทฤษฎีของหัวข้อนี้: {theory_line}\n:::\n{rest}"
            body.append(md + "\n")
            continue
        outputs = code_outputs[ci]
        ci += 1
        student = clean_code(render_code(text, student=True))
        if "# >>> TODO" in text:
            solution = clean_code(render_code(text, student=False))
            body.append(fence(student))
            body.append('::: {.callout-tip collapse="true" appearance="simple"}\n## ดูเฉลย\n\n'
                        + fence(solution) + ":::\n")
        elif student:
            body.append(fence(student))
        out = render_outputs(outputs, stem, ci)
        if out:
            body.append(out)
    if ci != len(code_outputs):
        raise RuntimeError(f"{stem}: source has {ci} code cells, solution has {len(code_outputs)} — rebuild notebooks")

    page = OUT / f"{stem}.qmd"
    front = f'---\ntitle: "{title}"\nsubtitle: "Walkthrough · notebook พร้อมผลลัพธ์และเฉลย"\n---\n\n'
    page.write_text(front + "\n".join(body), encoding="utf-8")
    return page


def main() -> None:
    if FIG.exists():
        shutil.rmtree(FIG)
    FIG.mkdir(parents=True)
    for stem in LABS_META:
        p = build(stem)
        print("wrote", p.relative_to(ROOT))
    print("figures:", len(list(FIG.glob("*.png"))))


if __name__ == "__main__":
    main()
